"""Filesystem portability checks without requiring FreeCAD or Qt."""
import os
from pathlib import Path
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest.mock import patch

from smbs_core.geometry_backend import freecad_bootstrap as bootstrap
from smbs_core.kinematics2d.developer_debug_log import desktop_directory
from tools.replay_native_component_blocker import resolve_replay_sources


class CrossPlatformPathsTests(unittest.TestCase):
    def test_xdg_desktop_with_spaces_and_unicode(self):
        with tempfile.TemporaryDirectory() as folder:
            home = Path(folder)
            config = home / 'config dir'
            config.mkdir()
            (config / 'user-dirs.dirs').write_text(
                '# generated by xdg-user-dirs\nXDG_DESKTOP_DIR="$HOME/Рабочий стол"\n',
                encoding='utf-8')
            with patch.object(sys, 'platform', 'linux'):
                self.assertEqual(desktop_directory(home, windows=False,
                    environ={'XDG_CONFIG_HOME': str(config)}), home / 'Рабочий стол')

    def test_macos_ignores_linux_desktop_configuration(self):
        with tempfile.TemporaryDirectory() as folder:
            home = Path(folder)
            (home / 'user-dirs.dirs').write_text('XDG_DESKTOP_DIR="$HOME/Wrong"')
            with patch.object(sys, 'platform', 'darwin'):
                self.assertEqual(desktop_directory(home, windows=False,
                    environ={'XDG_CONFIG_HOME': str(home)}), home / 'Desktop')

    def test_xdg_shell_substitution_is_not_used(self):
        with tempfile.TemporaryDirectory() as folder:
            home = Path(folder)
            (home / 'user-dirs.dirs').write_text('XDG_DESKTOP_DIR="$HOME/$(touch sentinel)"')
            with patch.object(sys, 'platform', 'linux'):
                self.assertEqual(desktop_directory(home, windows=False,
                    environ={'XDG_CONFIG_HOME': str(home)}), home / 'Desktop')

    def test_overrides_expand_home_and_environment(self):
        with patch.dict(os.environ, {'FREECAD_LIB': '~/FreeCAD lib',
                                    'FREECAD_MOD_SHEETMETAL': '$SMBS_TEST_MOD/SheetMetal',
                                    'SMBS_TEST_MOD': str(Path.home() / 'Mod') } ):
            self.assertEqual(bootstrap.get_freecad_lib_candidates()[0],
                             str(Path.home() / 'FreeCAD lib'))
            self.assertEqual(bootstrap.get_sheetmetal_mod_candidates()[0],
                             str(Path.home() / 'Mod' / 'SheetMetal'))

    def test_windows_installation_on_nonstandard_program_files_root(self):
        with tempfile.TemporaryDirectory() as folder:
            install = Path(folder) / 'Program Files' / 'FreeCAD 1.2'
            (install / 'bin').mkdir(parents=True)
            fake_os = SimpleNamespace(name='nt', path=os.path,
                environ={'ProgramFiles': str(install.parent)})
            with patch.object(bootstrap, 'os', fake_os), patch.object(sys, 'platform', 'win32'):
                candidates = bootstrap.get_freecad_lib_candidates()
            self.assertIn(str(install / 'bin'), candidates)

    def test_macos_user_application_bundle(self):
        with tempfile.TemporaryDirectory() as folder:
            home = Path(folder)
            lib = home / 'Applications' / 'FreeCAD 1.2.app' / 'Contents' / 'Resources' / 'lib'
            lib.mkdir(parents=True)
            with patch.object(Path, 'home', return_value=home), patch.object(sys, 'platform', 'darwin'):
                self.assertIn(str(lib), bootstrap.get_freecad_lib_candidates())

    def test_runtime_sheetmetal_directory(self):
        with tempfile.TemporaryDirectory() as folder:
            runtime = SimpleNamespace(getUserAppDataDir=lambda: folder)
            with patch.dict(sys.modules, {'FreeCAD': runtime}):
                self.assertIn(str(Path(folder) / 'Mod' / 'SheetMetal'),
                              bootstrap.get_sheetmetal_mod_candidates())

    def test_replay_foreign_paths_and_redirected_desktop(self):
        with tempfile.TemporaryDirectory() as folder:
            root = Path(folder)
            desktop = root / 'Рабочий стол'
            desktop.mkdir()
            (desktop / 'part.FCStd').touch()
            for kind in ('punch', 'die'):
                path = root / 'toollibrary' / kind
                path.mkdir(parents=True)
                (path / (kind + '.FCStd')).touch()
            for foreign in ('C:\\Users\\Other\\', '/Users/other/', '/home/other/',
                            '\\\\server\\share\\'):
                evidence = {kind + '_path': foreign + kind + '.FCStd'
                            for kind in ('part', 'punch', 'die')}
                with patch('tools.replay_native_component_blocker.desktop_directory',
                           return_value=desktop):
                    result = resolve_replay_sources(evidence, source_root=root)
                self.assertEqual(result['part'], (desktop / 'part.FCStd').resolve())
                self.assertEqual(result['punch'],
                    (root / 'toollibrary' / 'punch' / 'punch.FCStd').resolve())


if __name__ == '__main__':
    unittest.main()
